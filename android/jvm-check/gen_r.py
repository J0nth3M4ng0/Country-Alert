"""Writes a stand-in R class from the app's resources, so the app code can be
compiled without the Android SDK. A missing resource name fails the build."""
import os, re, sys

res = os.path.join(os.path.dirname(__file__), "..", "app", "src", "main", "res")
out = sys.argv[1]
ids, layouts, strings, drawables, xmls = set(), set(), set(), set(), set()
for name in os.listdir(os.path.join(res, "layout")):
    layouts.add(name[:-4])
    ids.update(re.findall(r'@\+id/(\w+)', open(os.path.join(res, "layout", name)).read()))
strings.update(re.findall(r'<string name="(\w+)"', open(os.path.join(res, "values", "strings.xml")).read()))
drawables.update(n[:-4] for n in os.listdir(os.path.join(res, "drawable")))
xmls.update(n[:-4] for n in os.listdir(os.path.join(res, "xml")))

n = [0x7f000000]
def block(kind, names):
    lines = []
    for x in sorted(names):
        n[0] += 1
        lines.append(f"        const val {x} = {n[0]}")
    return f"    object {kind} {{\n" + "\n".join(lines) + "\n    }\n"

os.makedirs(os.path.dirname(out), exist_ok=True)
with open(out, "w") as f:
    f.write("package com.countryalert.unrest\n\n// Generated by gen_r.py for the compile check only.\nobject R {\n")
    for kind, names in [("id", ids), ("layout", layouts), ("string", strings), ("drawable", drawables), ("xml", xmls)]:
        f.write(block(kind, names))
    f.write("}\n")
